"""The Python codec against the C one: docs/contracts/rf_trace_vectors.json is
generated by the firmware's rf_trace.c (scripts/gen_rf_trace_vectors.sh) and
pinned on the C side by test/test_rf_trace.c. Every vector must decode here
to the same fields, re-encode to the same bytes, and every refused vector
must be refused for the same reason."""

import json
import pathlib
import random

import pytest

from rftrace import codec

ROOT = pathlib.Path(__file__).resolve().parents[3]
VECTORS = json.loads((ROOT / "docs/contracts/rf_trace_vectors.json").read_text())


def unhex(s: str) -> bytes:
    return bytes.fromhex(s.replace(" ", ""))


def test_format_constants_match_c():
    f = VECTORS["format"]
    assert codec.MAGIC == unhex(f["magic"])
    assert codec.CMD == f["cmd"]
    assert codec.STATUS_OK == f["status"]
    assert codec.VERSION == f["version"]
    assert codec.BATCH_MAX == f["batch_max"]
    assert {codec.KIND_NAMES[k]: s for k, s in codec.REC_SIZE.items()} == f["record_sizes"]
    assert codec.KIND_IDS == f["kinds"]


@pytest.mark.parametrize("vec", VECTORS["frames"], ids=lambda v: v["name"])
def test_frame_vector_decodes_to_c_fields(vec):
    frame = codec.decode_frame(unhex(vec["hex"]))
    assert frame == {"version": vec["version"], "kind": vec["kind"], "records": vec["records"]}


@pytest.mark.parametrize("vec", VECTORS["frames"], ids=lambda v: v["name"])
def test_frame_vector_reencodes_to_c_bytes(vec):
    assert codec.encode_frame(vec["kind"], vec["records"]) == unhex(vec["hex"])


@pytest.mark.parametrize("vec", VECTORS["refused"], ids=lambda v: v["name"])
def test_refused_vector_refused_for_the_same_reason(vec):
    with pytest.raises(codec.TraceError) as e:
        codec.decode_frame(unhex(vec["hex"]))
    assert e.value.code == vec["error"]


def test_every_bit_flip_after_the_header_is_a_crc_error():
    good = unhex(VECTORS["frames"][1]["hex"])
    for i in range(codec.HDR, len(good)):
        for bit in range(8):
            b = bytearray(good)
            b[i] ^= 1 << bit
            with pytest.raises(codec.TraceError) as e:
                codec.decode_frame(bytes(b))
            assert e.value.code == "crc"


def test_stream_vector_frames_at_c_offsets():
    s = unhex(VECTORS["stream"]["hex"])
    found, pos = [], 0
    while True:
        status, start, length, _ = codec.scan(s, pos)
        if status != codec.FOUND:
            break
        found.append([start, length])
        pos = start + length
    assert found == VECTORS["stream"]["frames_at"]
    assert status == codec.PARTIAL
    assert len(s) - start == VECTORS["stream"]["keep_tail"]


def _split(stream, chunk):
    sc = codec.StreamScanner()
    items = []
    for i in range(0, len(stream), chunk):
        items += sc.feed(stream[i:i + chunk])
    return items, sc.pending()


@pytest.mark.parametrize("chunk", [1, 2, 7, 64, 4096])
def test_stream_scanner_any_chunking(chunk):
    s = unhex(VECTORS["stream"]["hex"])
    items, pending = _split(s, chunk)
    frames = [x for k, x in items if k == "frame"]
    text = b"".join(x for k, x in items if k == "text")
    assert [f["kind"] for f in frames] == ["tx", "periodic"]
    # Everything that is not a frame comes out as text, in order — the fake
    # header included — and the dangling "KR" is held back.
    (a0, l0), (a1, l1) = VECTORS["stream"]["frames_at"]
    assert text + pending == s[:a0] + s[a0 + l0:a1] + s[a1 + l1:]
    assert pending == b"KR"


def test_resync_through_random_console_noise():
    rng = random.Random(0x5EED)
    frames = [unhex(v["hex"]) for v in VECTORS["frames"]]
    noise_words = [b"I (123) kbd: HB up=4 s ", "é → ─ ".encode(), b"\x1b[0;33mW\x1b[0m ",
                   b"K", b"KR", b"KR\xba", b"KR\xba\x00\x10\x00", b"\r\n", bytes([0x4B, 0x52, 0xBA, 0, 0xFF])]
    stream, expect = b"", []
    for _ in range(200):
        stream += b"".join(rng.choice(noise_words) for _ in range(rng.randrange(0, 6)))
        f = rng.choice(frames)
        stream += f
        expect.append(codec.decode_frame(f))
    items, _ = _split(stream, 13)
    assert [x for k, x in items if k == "frame"] == expect


def test_crc8_is_the_project_crc():
    # docs/CDC_BINARY_PROTOCOL.md reference vectors (test_cdc_rx_feed.c)
    assert codec.crc8(b"") == 0x00
    assert codec.crc8(b"\x01") == 0x31
    assert codec.crc8(b"KS") == 0xBE
